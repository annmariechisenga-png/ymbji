package com.localgov.web;

import org.h2.tools.RunScript;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;

import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertThrows;

class OrganisationStructureImportStagingMigrationTest {

    private Connection connection;

    @BeforeEach
    void setUp() throws Exception {
        connection = DriverManager.getConnection(
            "jdbc:h2:mem:org_staging;DB_CLOSE_DELAY=-1"
        );

        try (var statement = connection.createStatement()) {
            statement.execute("DROP TABLE IF EXISTS organisation_structure_import_staging");

            statement.execute("""
                CREATE TABLE organisation_structure_import_staging (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    source_node_type VARCHAR(30) NOT NULL,
                    salary_scale VARCHAR(20),
                    establishment_quantity INTEGER,
                    is_established BOOLEAN NOT NULL DEFAULT FALSE,
                    is_funded BOOLEAN NOT NULL DEFAULT FALSE,
                    is_frozen BOOLEAN NOT NULL DEFAULT FALSE,
                    is_active BOOLEAN NOT NULL DEFAULT TRUE,
                    CONSTRAINT chk_org_import_frozen_active
                        CHECK (is_frozen = FALSE OR is_active = TRUE),
                    CONSTRAINT chk_org_import_letter_scale_frozen
                        CHECK (
                            salary_scale NOT BETWEEN 'A' AND 'N'
                            OR is_frozen = TRUE
                        ),
                    CONSTRAINT chk_org_import_ungraded_scale_frozen
                        CHECK (
                            salary_scale <> 'LGSS'
                            OR is_frozen = TRUE
                        )
                )
                """);
        }

        RunScript.execute(
            connection,
            new InputStreamReader(
                getClass().getResourceAsStream(
                    "/db/migration/V70__introduce_attached_position_state.sql"
                ),
                StandardCharsets.UTF_8
            )
        );
    }

    @Test
    void permitsSalaryScalesWithoutDerivingFrozenOrAttachedStates() {
        assertDoesNotThrow(() ->
            insert("'A'", false, false, true)
        );

        assertDoesNotThrow(() ->
            insert("'N'", false, false, true)
        );

        assertDoesNotThrow(() ->
            insert("'LGSS'", false, false, true)
        );

        assertDoesNotThrow(() ->
            insert("'LGSS/06'", false, false, true)
        );

        assertDoesNotThrow(() ->
            insert("'A'", false, true, true)
        );

        assertDoesNotThrow(() ->
            insert("'M'", true, false, true)
        );
    }

    @Test
    void requiresFrozenAndAttachedPositionsToRemainActive() {
        assertThrows(SQLException.class, () ->
            insert("'M'", true, false, false)
        );

        assertThrows(SQLException.class, () ->
            insert("'A'", false, true, false)
        );
    }

    private void insert(
        String salaryScale,
        boolean frozen,
        boolean attached,
        boolean active
    ) throws SQLException {

        try (var statement = connection.createStatement()) {
            statement.executeUpdate("""
                INSERT INTO organisation_structure_import_staging
                    (
                        source_node_type,
                        salary_scale,
                        is_frozen,
                        is_attached,
                        is_active,
                        establishment_quantity,
                        is_established
                    )
                VALUES
                    (
                        'POSITION',
                        %s,
                        %s,
                        %s,
                        %s,
                        1,
                        TRUE
                    )
                """.formatted(
                    salaryScale,
                    frozen,
                    attached,
                    active
                ));
        }
    }
}
